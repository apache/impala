class TestWebserverSaml(TestSamlBase):
  """
  Tests for a client using SAML2 browser profile against the Impala webserver.

  These tests simulate the SAML2 browser profile workflow by sending HTTP requests
  to Impala's webserver port (default 25000):

  1. A GET request to the webserver port.
     - The test client sends a GET request to the webserver.
     - Impala responds with a 302 redirect to the SSO service (IDP_URL), including
       encoded SAMLRequest and RelayState parameters.
     - This simulates the browser being redirected to the identity provider.

  2. A POST request to the SAML2 callback URL (SP_CALLBACK_URL) containing an encoded
     AuthNResponse and the RelayState as content.
     - Normally, this would come from the browser after authentication at the IDP.
     - Impala validates the AuthNResponse and responds with a 302 redirect and a
       Set-Cookie header containing the authentication cookie.

  3. (Not implemented here) After obtaining the auth cookie, a real client would send
     authenticated requests to the webserver. These tests focus on the SAML2
     authentication flow only.
  """

