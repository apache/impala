  WS_PORT = 25000

  SSO_ARGS = ((TestSamlBase.SSO_ARGS_COMMON
               + " --webserver_saml2_idp_metadata=%s/saml2_sso_metadata.xml"
               + " --webserver_saml2_sp_callback_url=%s")
              % (TestSamlBase.CERT_DIR, SP_CALLBACK_URL))

