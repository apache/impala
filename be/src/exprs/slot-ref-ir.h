#pragma once

#include "runtime/descriptors.h"
#include "udf/udf-internal.h"

namespace impala {

class TupleRow;

/// The cross-compiled parts of SlotRef, defined in slot-ref-ir.cc. They are not members
/// of SlotRef because slot-ref.h includes the LLVM headers, which are not available when
/// cross-compiling to IR. Being static members (and not free functions) also makes the
/// compiler reject a definition that does not match its declaration.
class SlotRefIr {
 public:
  /// Reads the VARIANT slot at 'slot_offset' of the tuple at 'tuple_idx' in 'row'. The
  /// tuple pointer is only checked if 'tuple_is_nullable' is true. Called by
  /// SlotRef::GetVariantValInterpreted() and from the IR generated by
  /// SlotRef::CodegenVariantValue().
  static impala_udf::VariantVal ReadVariantVal(const TupleRow* row, int tuple_idx,
      bool tuple_is_nullable, NullIndicatorOffset null_indicator_offset,
      int slot_offset);
};

} // namespace impala
